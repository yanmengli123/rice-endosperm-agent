"""文献深读输出策略（批次 1）。

为文献专属会话（闸门当前仅对 paper 会话生效）提供"深读式"回答形态的策略文本，作为
``answer_context_builder`` 的 **additive 尾段**注入模型上下文。

设计约束：

- **additive，不覆盖**：本策略只规定"怎么组织回答"，不改写、不豁免任何
  locator/定位类硬约束（如 ``page_claim_allowed=False`` 时禁止给页码）。定位
  题的硬约束永远优先于本策略。
- **事实仍须绑证据**：地图/策略都只是输出形态引导；断言仍必须来自回答实际
  引用的原文 ``evidence``，证据不足必须明说"当前证据不足"，禁止用常识硬答。
- **门禁不豁免**：深读策略不是 source_guard / 血统校验的豁免通道。
- 闸门外会话（普通科研问答）不引用本模块，输出逐字节不变。
"""

from __future__ import annotations

#: 文献深读输出策略（结论先行 -> 分域 -> 证据细节 -> 局限）。结论先行与方法/结果/
#: 讨论分域是豆包级文献体验的核心感知；"证据不足明说"是防幻觉硬规则。
LITERATURE_DEEPREAD_POLICY = """【文献深读作答策略】
1. 结论先行：开头一句给出直接回答/核心结论，再展开论证。
2. 分域组织：涉及方法、结果、讨论时分别归入对应小节作答，不要混编。
3. 证据绑定：每个要点都要落到本回答引用的〔证据E#〕；不得复述导航地图里的章节名或图表编号充当事实，地图只用来定位。
4. 证据不足即明说：本轮证据不足时回答"当前证据不足以回答"，不得把未召回等同于论文未提供，不得宣称已读完全文。
只有具备完整覆盖核验时才可断言原文未提供。不得用常识或训练记忆代答，不得编造页码或数据。
5. 可引用时给出定位：正文中的定位结论仍受 answer_policy 约束，未经授权不得擅自给出页码、文献名或图/表编号。"""


def build_literature_deepread_section() -> str:
    """返回文献深读策略文本（供 answer_context_builder additive 尾段复用）。"""
    return LITERATURE_DEEPREAD_POLICY
